it("keeps dynamic catalog patterns separate from explicit members on import and export", () => {
  const group = importRoutingGroup(
    JSON.stringify({
      name: "Future catalog",
      members: [],
      match: ["alpha/*", "re:^beta/model-"],
    }),
    providers,
  );
  expect(group.members).toEqual([]);
  expect(group.defaultMemberId).toBe("");
  expect(group.match).toEqual(["alpha/*", "re:^beta/model-"]);
  const copy = importRoutingGroup(JSON.stringify(group), providers);
  expect(copy.match).toEqual(group.match);
  expect(copy.members).toEqual([]);
  expect(() =>
    importRoutingGroup(
      JSON.stringify({ name: "Empty", members: [] }),
      providers,
    ),
  ).toThrow();
  expect(() =>
    importRoutingGroup(
      JSON.stringify({ name: "Invalid", members: [], match: ["re:["] }),
      providers,
    ),
  ).toThrow();
});

