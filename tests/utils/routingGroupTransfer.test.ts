it("round trips an exported Vary group with fresh identities and intact references", () => {
  const original = fixtureGroup();
  original.name = "Synthetic transfer";
  original.revision = 7;
  original.rules = [
    {
      id: "original-rule",
      name: "Synthetic intent",
      description: "Synthetic classification",
      enabled: true,
      targetMemberId: original.members[1].id,
    },
  ];
  const imported = importRoutingGroup(
    JSON.stringify({
      format: "vary-routing-group",
      version: 1,
      group: original,
    }),
    providers,
  );
  expect(imported.id).not.toBe(original.id);
  expect(imported.revision).toBe(0);
  expect(imported.members[0].id).not.toBe(original.members[0].id);
  expect(imported.defaultMemberId).toBe(imported.members[0].id);
  expect(imported.fallbackMemberIds).toEqual([imported.members[1].id]);
  expect(imported.rules[0].id).not.toBe("original-rule");
  expect(imported.rules[0].targetMemberId).toBe(imported.members[1].id);
});
