it("imports reference timeouts, patience, affinity and disabled members without losing their identities", () => {
  const group = importRoutingGroup(
    JSON.stringify({
      name: "Synthetic controls",
      members: ["alpha/model-a", "beta/model-b"],
      firstToken: 4,
      patience: 30,
      affinity: "strict",
      off: ["alpha/model-a"],
    }),
    providers,
  );
  expect(group).toMatchObject({
    firstToken: 4,
    patience: 30,
    affinity: "strict",
  });
  expect(group.off).toEqual([group.members[0].id]);
  const copy = importRoutingGroup(JSON.stringify(group), providers);
  expect(copy.off).toEqual([copy.members[0].id]);
  expect(copy.off).not.toEqual(group.off);
});

