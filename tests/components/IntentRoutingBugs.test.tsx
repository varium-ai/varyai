import {
  fireEvent,
  render,
  screen,
  waitFor,
  within,
} from "@testing-library/react";
import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import { afterEach, beforeEach, expect, it, vi } from "vitest";
import userEvent from "@testing-library/user-event";
import { copyText } from "@/lib/clipboard";
import { toast } from "sonner";
vi.mock("@/lib/clipboard", () => ({ copyText: vi.fn() }));
vi.mock("sonner", () => ({ toast: { success: vi.fn(), error: vi.fn() } }));
import { IntentRoutingPanel } from "@/components/routing/IntentRoutingPanel";
import { intentRoutingApi, type RoutingGroup } from "@/lib/api/intentRouting";
vi.mock("@/components/routing/RoutingClient", () => ({
  RoutingClient: () => null,
}));
vi.mock("@/lib/api/intentRouting", () => ({
  intentRoutingApi: {
    list: vi.fn(),
    providers: vi.fn(),
    discoverCatalogs: vi.fn(),
    remove: vi.fn(),
    save: vi.fn(),
    autoGroupSkip: vi.fn(),
  },
}));
const group: RoutingGroup = {
  id: "fixture",
  name: "Synthetic group",
  revision: 1,
  client: "global",
  enabled: true,
  intentRecognitionEnabled: false,
  classifierTarget: null,
  classificationBudgetMs: 2000,
  members: [
    { id: "first", providerId: "provider", modelId: "first" },
    { id: "removed", providerId: "provider", modelId: "removed" },
  ],
  defaultMemberId: "first",
  fallbackMemberIds: ["removed"],
  rules: [],
  routing: "manual",
  manualMemberId: "first",
};
function mount() {
  return render(
    <QueryClientProvider
      client={
        new QueryClient({ defaultOptions: { queries: { retry: false } } })
      }
    >
      <IntentRoutingPanel />
    </QueryClientProvider>,
  );
}
beforeEach(() => {
  vi.clearAllMocks();
  vi.mocked(intentRoutingApi.list).mockResolvedValue({
    groups: [group],
    autoCreate: false,
    omittedGroups: 0,
  });
  vi.mocked(intentRoutingApi.providers).mockResolvedValue([
    {
      id: "provider",
      name: "Synthetic provider",
      taskEligible: true,
      classifierEligible: false,
      models: [{ id: "first", name: "first" }],
    },
  ]);
  vi.mocked(intentRoutingApi.autoGroupSkip).mockResolvedValue([]);
});
afterEach(() => vi.restoreAllMocks());
it.each([false, true])(
  "reports share outcome safely when copying fails=%s",
  async (failed) => {
    vi.mocked(copyText).mockImplementation(async () => {
      if (failed) throw new Error("synthetic-private-detail");
    });
    mount();
    await userEvent.click(
      await screen.findByRole("button", {
        name: "routingPage.more Synthetic group",
      }),
    );
    await userEvent.click(
      await screen.findByRole("menuitem", { name: "routingPage.copyShare" }),
    );
    if (failed)
      expect(await screen.findByRole("alert")).toHaveTextContent(
        "intentRouting.failed",
      );
    else {
      expect(copyText).toHaveBeenCalledOnce();
      expect(toast.success).toHaveBeenCalledWith("routingPage.copied");
    }
    expect(document.body).not.toHaveTextContent("synthetic-private-detail");
  },
);

it("disables a manual route member removed from the provider catalog", async () => {
  mount();
  expect(await screen.findByRole("radio", { name: "removed" })).toBeDisabled();
  expect(screen.getByRole("radio", { name: "first" })).toBeEnabled();
});
it.each([false, true])(
  "archives removed groups with automatic discovery=%s",
  async (automatic) => {
    const auto = automatic
      ? { ...group, id: "auto-fixture", revision: 0, autoGenerated: true }
      : group;
    vi.mocked(intentRoutingApi.list).mockResolvedValue({
      groups: [auto],
      autoCreate: automatic,
      omittedGroups: 0,
    });
    vi.mocked(intentRoutingApi.remove).mockImplementation(async () => {
      vi.mocked(intentRoutingApi.list).mockResolvedValue({
        groups: [],
        autoCreate: automatic,
        omittedGroups: 0,
        removedGroups: [{ id: auto.id, name: auto.name }],
      });
    });
    mount();
    fireEvent.click(
      await screen.findByRole("button", { name: "common.delete" }),
    );
    const confirm = screen.getByRole("dialog", { name: "common.delete" });
    fireEvent.click(
      within(confirm).getByRole("button", {
        name: "intentRouting.confirmDelete",
      }),
    );
    await waitFor(() =>
      expect(intentRoutingApi.remove).toHaveBeenCalledWith(
        auto.id,
        auto.revision,
      ),
    );
    expect(
      await screen.findByRole("button", {
        name: "intentRouting.removedGroups",
      }),
    ).toBeVisible();
  },
);
it("shows an unavailable template's add action with its unmet requirement", async () => {
  vi.mocked(intentRoutingApi.list).mockResolvedValue({
    groups: [],
    autoCreate: false,
    omittedGroups: 0,
  });
  vi.mocked(intentRoutingApi.providers).mockResolvedValue([]);
  mount();
  const intro = await screen.findByText("routingPage.templateHint");
  const cards = intro.parentElement!;
  const actions = within(cards).getAllByRole("button", {
    name: "routingPage.addTemplate",
  });
  expect(actions.length).toBeGreaterThan(0);
  for (const action of actions) expect(action).toBeDisabled();
});

it.each([false, true])(
  "reports JSON export outcome safely when download fails=%s",
  async (failed) => {
    const createUrl = vi.fn(() => "blob:synthetic-export");
    vi.stubGlobal(
      "URL",
      class extends URL {
        static createObjectURL = createUrl;
        static revokeObjectURL = vi.fn();
      },
    );
    const click = vi
      .spyOn(HTMLAnchorElement.prototype, "click")
      .mockImplementation(function (this: HTMLAnchorElement) {
        expect(this.download).toBe("vary-routing-group-fixture.json");
        if (failed) throw new Error("synthetic-private-export");
      });
    try {
      mount();
      await userEvent.click(
        await screen.findByRole("button", {
          name: "routingPage.more Synthetic group",
        }),
      );
      await userEvent.click(
        await screen.findByRole("menuitem", { name: "routingPage.export" }),
      );
      if (failed)
        expect(await screen.findByRole("alert")).toHaveTextContent(
          "intentRouting.failed",
        );
      else
        expect(await screen.findByRole("status")).toHaveTextContent(
          "routingPage.exportStarted",
        );
      expect(createUrl).toHaveBeenCalledWith(expect.any(Blob));
      expect(click).toHaveBeenCalledOnce();
      expect(document.body).not.toHaveTextContent("synthetic-private-export");
    } finally {
      vi.unstubAllGlobals();
    }
  },
);
