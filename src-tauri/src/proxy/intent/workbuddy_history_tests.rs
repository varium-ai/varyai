#[tokio::test]
#[serial_test::serial]
async fn workbuddy_imported_complete_history_keeps_ownership_for_the_next_tool_round(
) -> Result<(), Box<dyn std::error::Error>> {
    let _security = security();
    for source_format in ["openai_chat", "gemini_native"] {
        for streaming in [false, true] {
            let mut fixture = Fixture::with_follow_up(source_format, 1, true).await?;
            fixture.seed_prior_model().await?;
            let mut request = history(&fixture.grok_alias, streaming);
            let response = fixture
                .client
                .post(&fixture.root)
                .bearer_auth(TOKEN)
                .json(&request)
                .send()
                .await?;
            assert_eq!(response.status(), StatusCode::OK);
            let wire = response.text().await?;
            let assistant = if streaming {
                let mut tool = call(THIRD_ID, 3);
                tool["id"] = Value::Null;
                tool["function"]["name"] = Value::Null;
                let mut arguments = String::new();
                for data in wire.lines().filter_map(|line| line.strip_prefix("data: ")) {
                    if data == "[DONE]" {
                        continue;
                    }
                    let frame: Value = serde_json::from_str(data)?;
                    if let Some(parts) = frame["choices"][0]["delta"]["tool_calls"].as_array() {
                        for part in parts {
                            assert_eq!(part["index"], 0);
                            if part["id"].as_str().is_some() {
                                tool["id"] = part["id"].clone();
                            }
                            if part["function"]["name"].as_str().is_some() {
                                tool["function"]["name"] = part["function"]["name"].clone();
                            }
                            if let Some(fragment) = part["function"]["arguments"].as_str() {
                                arguments.push_str(fragment);
                            }
                        }
                    }
                }
                tool["function"]["arguments"] = json!(arguments);
                json!({"role":"assistant","content":null,"tool_calls":[tool]})
            } else {
                let first: Value = serde_json::from_str(&wire)?;
                first["choices"][0]["message"].clone()
            };
            assert_eq!(assistant["tool_calls"][0]["id"], THIRD_ID);
            assert_eq!(
                assistant["tool_calls"][0]["function"]["name"],
                "synthetic_tool_3"
            );
            assert_eq!(
                serde_json::from_str::<Value>(
                    assistant["tool_calls"][0]["function"]["arguments"]
                        .as_str()
                        .ok_or("missing new call arguments")?
                )?,
                arguments(3)
            );
            let first_sent = tokio::time::timeout(Duration::from_secs(2), fixture.requests.recv())
                .await?
                .ok_or("missing first Grok request")?;
            assert_eq!(
                first_sent["input"]
                    .as_array()
                    .ok_or("missing imported history")?
                    .iter()
                    .filter(|item| item["type"] == "function_call")
                    .count(),
                2
            );
            let messages = request["messages"]
                .as_array_mut()
                .ok_or("missing history messages")?;
            messages.push(assistant);
            messages.push(
                json!({"role":"tool","tool_call_id":THIRD_ID,"content":"Synthetic third result"}),
            );
            let response = fixture
                .client
                .post(&fixture.root)
                .bearer_auth(TOKEN)
                .json(&request)
                .send()
                .await?;
            assert_eq!(
                response.status(),
                StatusCode::OK,
                "{source_format} imported history lost scope ownership"
            );
            assert!(response.text().await?.contains("Synthetic Grok answer"));
            let sent = tokio::time::timeout(Duration::from_secs(2), fixture.requests.recv())
                .await?
                .ok_or("missing next Grok request")?;
            let input = sent["input"]
                .as_array()
                .ok_or("missing next Responses input")?;
            for (id, index, result) in [
                (FIRST_ID, 1, "Synthetic first result"),
                (SECOND_ID, 2, "Synthetic second result"),
                (THIRD_ID, 3, "Synthetic third result"),
            ] {
                let call = input
                    .iter()
                    .find(|item| item["type"] == "function_call" && item["call_id"] == id)
                    .ok_or("missing preserved call")?;
                assert_eq!(
                    serde_json::from_str::<Value>(
                        call["arguments"]
                            .as_str()
                            .ok_or("missing preserved arguments")?
                    )?,
                    arguments(index)
                );
                assert!(input
                    .iter()
                    .any(|item| item["type"] == "function_call_output"
                        && item["call_id"] == id
                        && item["output"] == result));
            }
            assert_eq!(fixture.sends.load(Ordering::SeqCst), 2);
            fixture.stop().await?;
        }
    }
    Ok(())
}

#[tokio::test]
#[serial_test::serial]
async fn workbuddy_complete_tool_history_preserves_existing_scope_conflicts(
) -> Result<(), Box<dyn std::error::Error>> {
    let _security = security();
    for scenario in ["mixed_owners", "duplicate_owners"] {
        let fixture = Fixture::new("openai_chat").await?;
        let scope = fixture.runtime.conversations.acquire(
            "agent:workbuddy",
            &fixture.grok.bindings,
            Some("synthetic-first-scope"),
            &json!({}),
        )?;
        {
            let mut bindings = scope.bindings.lock().unwrap();
            remember(&mut bindings.calls, "call", FIRST_ID, 0);
            if scenario != "mixed_owners" {
                remember(&mut bindings.calls, "call", SECOND_ID, 0);
            }
        }
        {
            let other = fixture.runtime.conversations.acquire(
                "agent:workbuddy",
                &fixture.grok.bindings,
                Some("synthetic-second-scope"),
                &json!({}),
            )?;
            let mut bindings = other.bindings.lock().unwrap();
            remember(&mut bindings.calls, "call", SECOND_ID, 0);
            if scenario == "duplicate_owners" {
                remember(&mut bindings.calls, "call", FIRST_ID, 0);
            }
        }
        let response = fixture
            .client
            .post(&fixture.root)
            .bearer_auth(TOKEN)
            .json(&history(&fixture.grok_alias, false))
            .send()
            .await?;
        assert_eq!(response.status(), StatusCode::CONFLICT, "{scenario}");
        let body: Value = response.json().await?;
        assert_eq!(
            body["error"]["code"], "routing_ambiguous_continuation",
            "{scenario}"
        );
        assert_eq!(
            fixture.sends.load(Ordering::SeqCst),
            0,
            "{scenario} reached the upstream"
        );
        fixture.stop().await?;
    }
    Ok(())
}

#[tokio::test]
async fn workbuddy_portable_history_does_not_bypass_a_restored_destination_change(
) -> Result<(), Box<dyn std::error::Error>> {
    let dir = tempfile::tempdir()?;
    let store =
        continuation::Store::load(dir.path().join("state.json"), dir.path().join("state.key"))
            .await?;
    let original = session(
        "http://synthetic.invalid/v1",
        "new-grok-model",
        "grok-4.5",
        "openai_responses",
    );
    let projection = super::super::group_forward::canonical_request(
        Protocol::Chat,
        &history(&original.group.alias(), false),
        "/v1/chat/completions",
    )?;
    assert!(completed_tool_history(&projection));
    let conversations = scopes::Conversations::default();
    let scope = conversations.acquire_durable_with_history(
        "agent:workbuddy",
        &original,
        None,
        &projection,
        Some(store.clone()),
        true,
    )?;
    scope.bindings.lock().unwrap().observe(
        &json!({"output":[{"type":"function_call","call_id":FIRST_ID},{"type":"function_call","call_id":SECOND_ID}]}),
        0,
    );
    store.flush().await?;
    drop(scope);
    drop(conversations);
    let mut changed = (*original).clone();
    changed.targets[0].url = "http://synthetic.invalid/replaced/responses".parse()?;
    assert_ne!(
        original.targets[0].continuation_destination(),
        changed.targets[0].continuation_destination()
    );
    let restored = scopes::Conversations::default().acquire_durable_with_history(
        "agent:workbuddy",
        &changed,
        None,
        &projection,
        Some(store),
        true,
    );
    assert_eq!(restored.err(), Some("routing_unknown_continuation"));
    Ok(())
}
