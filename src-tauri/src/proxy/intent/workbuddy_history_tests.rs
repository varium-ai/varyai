#[serial_test::serial]
async fn workbuddy_smart_template_routes_easy_text_when_classifier_finishes_before_deadline(
) -> Result<(), Box<dyn std::error::Error>> {
    let _security = security();
    let mut fixture = Fixture::with_targets("openai_chat", 2).await?;
    let mut menu = (*fixture.runtime.global_snapshot()?.ok_or("missing menu")?).clone();
    let group = Arc::make_mut(
        menu.groups
            .get_mut(&fixture.grok_alias)
            .ok_or("missing group")?,
    );
    let mut base = group.targets[0].url.clone();
    base.set_path("/v1");
    group.classifier = Some(crate::provider::Provider::with_id(
        "classifier".into(),
        "Synthetic classifier".into(),
        json!({"apiFormat":"gemini_native","auth":{"OPENAI_API_KEY":"synthetic-key"},
            "config":format!("model_provider = \"fixture\"\n[model_providers.fixture]\nbase_url = \"{base}\"\nwire_api = \"gemini\""),
            "modelCatalog":{"models":[{"model":"gemini-3.6-flash","reasoningLevels":["minimal","low","high"]}]}}),
        None,
    ));
    group.group.intent_recognition_enabled = true;
    group.group.members[1].model_id = "glm-synthetic".into();
    group.targets[1].model = "glm-synthetic".into();
    group.group.classifier_target = Some(crate::services::intent_routing::Target {
        provider_id: "classifier".into(),
        model_id: "gemini-3.6-flash".into(),
    });
    group.group.affinity = "turn".into();
    group.group.template = Some(crate::services::intent_routing::RoutingTemplate::Smart);
    group.group.rules = serde_json::from_value(json!([
        {"id":"compaction","name":"Compaction","description":"","enabled":true,"targetMemberId":"direct","conditions":{"compact":true}},
        {"id":"hard","name":"Hard","description":"Complex tasks","enabled":true,"targetMemberId":"direct"},
        {"id":"easy","name":"Easy","description":"Short direct replies","enabled":true,"targetMemberId":"other-1"}
    ]))?;
    fixture
        .runtime
        .connections
        .install(&crate::services::agent_connections::Receipt {
            app: "workbuddy-ai".into(),
            token: TOKEN.into(),
            model: fixture.grok_alias.clone(),
            model_map: Default::default(),
            visible_models: None,
            files: vec![],
            suspended: false,
            applied_at_ms: None,
        })?;
    let body =
        json!({"model":fixture.grok_alias,"messages":[{"role":"user","content":"回答hello"}]});
    for (budget, selected, outcome) in [
        (5000, "grok-4.5", "timeout"),
        (10000, "glm-synthetic", "matched"),
    ] {
        Arc::make_mut(
            menu.groups
                .get_mut(&fixture.grok_alias)
                .ok_or("missing group")?,
        )
        .group
        .classification_budget_ms = budget;
        fixture.runtime.set_global(menu.clone(), 0)?;
        for agent in ["workbuddy", "workbuddy-ai"] {
            fixture
                .client
                .post(fixture.root.replace("/workbuddy/", &format!("/{agent}/")))
                .bearer_auth(TOKEN)
                .json(&body)
                .send()
                .await?
                .error_for_status()?
                .bytes()
                .await?;
            assert_eq!(
                fixture
                    .requests
                    .recv()
                    .await
                    .ok_or("missing task forward")?["model"],
                selected
            );
            let traces = fixture.runtime.traces.snapshot();
            let route = traces.first().ok_or("missing trace")?;
            assert_eq!(
                route
                    .steps
                    .iter()
                    .any(|step| step.kind == trace::Kind::Rule),
                outcome == "matched"
            );
            assert_eq!(
                serde_json::to_value(route)?["classificationOutcome"],
                outcome
            );
        }
    }

    let group = Arc::make_mut(
        menu.groups
            .get_mut(&fixture.grok_alias)
            .ok_or("missing group")?,
    );
    for target in &mut group.targets {
        target.url.set_path("/smart-chat-completions");
        target
            .upstream
            .as_mut()
            .ok_or("missing provider")?
            .meta
            .get_or_insert_with(Default::default)
            .api_format = Some("openai_chat".into());
    }
    fixture.runtime.set_global(menu, 0)?;
    for agent in ["workbuddy", "workbuddy-ai"] {
        let mut messages = vec![json!({"role":"user","content":"Synthetic hard task"})];
        for expected in ["grok-4.5", "glm-synthetic"] {
            let body = fixture
                .client
                .post(fixture.root.replace("/workbuddy/", &format!("/{agent}/")))
                .bearer_auth(TOKEN)
                .header("x-session-id", "synthetic-smart-conversation")
                .json(&json!({"model":fixture.grok_alias,"stream":true,"messages":messages}))
                .send()
                .await?
                .error_for_status()?
                .text()
                .await?;
            assert!(body.contains("Synthetic answer"));
            assert_eq!(
                fixture
                    .requests
                    .recv()
                    .await
                    .ok_or("missing task forward")?["model"],
                expected
            );
            assert_eq!(
                fixture
                    .runtime
                    .traces
                    .snapshot()
                    .first()
                    .and_then(|route| route.classification_outcome.as_deref()),
                Some("matched")
            );
            messages.extend([
                json!({"role":"assistant","content":"Synthetic answer"}),
                json!({"role":"user","content":"Synthetic easy task"}),
            ]);
        }
    }
    fixture.stop().await
}

#[tokio::test]
#[serial_test::serial]
async fn workbuddy_visible_chat_resumes_when_a_group_member_is_removed(
) -> Result<(), Box<dyn std::error::Error>> {
    let _security = security();
    for agent in ["workbuddy", "workbuddy-ai"] {
        for (removed, streaming) in [(0, false), (0, true), (2, false), (2, true)] {
            let mut fixture = Fixture::with_targets("openai_chat", 3).await?;
            let endpoint = fixture.root.replace("/workbuddy/", &format!("/{agent}/"));
            fixture
                .runtime
                .connections
                .install(&crate::services::agent_connections::Receipt {
                    app: agent.into(),
                    token: TOKEN.into(),
                    model: fixture.grok_alias.clone(),
                    model_map: Default::default(),
                    visible_models: None,
                    files: vec![],
                    suspended: false,
                    applied_at_ms: None,
                })?;
            let dir = tempfile::tempdir()?;
            fixture
                .runtime
                .prepare_continuations(dir.path().join("continuations.json"))
                .await;
            let mut request = json!({"model":fixture.grok_alias,"stream":streaming,"messages":[
                {"role":"user","content":"Synthetic opening"}
            ]});
            let send = |body: &Value| {
                fixture
                    .client
                    .post(&endpoint)
                    .bearer_auth(TOKEN)
                    .header("x-session-id", "synthetic-workbuddy-session")
                    .json(body)
                    .send()
            };
            let response = send(&request).await?;
            assert_eq!(response.status(), StatusCode::OK);
            assert!(response.text().await?.contains("Synthetic Grok answer"));
            assert_eq!(
                fixture.requests.recv().await.ok_or("missing opening")?["model"],
                "grok-4.5"
            );
            fixture.runtime.flush_continuations().await;

            let mut menu = (*fixture
                .runtime
                .global_snapshot()?
                .ok_or("missing synthetic menu")?)
            .clone();
            let group = Arc::make_mut(
                menu.groups
                    .get_mut(&fixture.grok_alias)
                    .ok_or("missing synthetic route")?,
            );
            group.bindings = Arc::default();
            group.targets.remove(removed);
            group.group.members.remove(removed);
            // Make the unbound route prefer the fallback even when the old owner survives.
            group.group.default_member_id = "other-1".into();
            group.group.fallback_member_ids = group
                .group
                .members
                .iter()
                .filter(|member| member.id != group.group.default_member_id)
                .map(|member| member.id.clone())
                .collect();
            fixture.runtime.set_global(menu, 0)?;

            request["messages"]
                .as_array_mut()
                .ok_or("missing synthetic messages")?
                .extend([
                    json!({"role":"assistant","content":"Synthetic Grok answer"}),
                    json!({"role":"user","content":"Synthetic follow-up"}),
                ]);
            let mut sealed = request.clone();
            sealed["messages"][1]["reasoning_details"] =
                json!([{"type":"reasoning.encrypted","data":"synthetic-sealed-state"}]);
            let rerouted = send(&sealed).await?;
            assert_eq!(rerouted.status(), StatusCode::OK);
            assert_eq!(fixture.sends.load(Ordering::SeqCst), 2);
            let _ = fixture.requests.recv().await.ok_or("missing rerouted")?;

            let resumed = send(&request).await?;
            assert_eq!(
                resumed.status(),
                StatusCode::OK,
                "{agent}, removed={removed}, stream={streaming}"
            );
            assert!(resumed.text().await?.contains("Synthetic Grok answer"));
            let forwarded = fixture.requests.recv().await.ok_or("missing follow-up")?;
            assert_eq!(
                forwarded["model"],
                if removed == 0 {
                    "grok-synthetic-1"
                } else {
                    "grok-4.5"
                }
            );
            assert!(forwarded["input"]
                .as_array()
                .is_some_and(|items| items.len() == 3));
            fixture.stop().await?;
        }
    }
    Ok(())
}

#[tokio::test]
#[serial_test::serial]
async fn workbuddy_visible_chat_resumes_after_a_saved_target_configuration_refresh(
) -> Result<(), Box<dyn std::error::Error>> {
    let _security = security();
    for (agent, streaming) in [
        ("workbuddy", false),
        ("workbuddy", true),
        ("workbuddy-ai", false),
        ("workbuddy-ai", true),
    ] {
        let mut fixture = Fixture::new("openai_chat").await?;
        if agent == "workbuddy-ai" {
            fixture.root = fixture.root.replace("/workbuddy/", "/workbuddy-ai/");
            fixture
                .runtime
                .connections
                .install(&crate::services::agent_connections::Receipt {
                    app: agent.into(),
                    token: TOKEN.into(),
                    model: fixture.grok_alias.clone(),
                    model_map: Default::default(),
                    visible_models: None,
                    files: vec![],
                    suspended: false,
                    applied_at_ms: None,
                })?;
        }
        let dir = tempfile::tempdir()?;
        fixture
            .runtime
            .prepare_continuations(dir.path().join("continuations.json"))
            .await;
        let mut request = json!({"model":fixture.grok_alias,"stream":streaming,"messages":[
            {"role":"user","content":"Synthetic opening"}
        ]});
        let first = fixture
            .client
            .post(&fixture.root)
            .bearer_auth(TOKEN)
            .json(&request)
            .send()
            .await?;
        assert_eq!(first.status(), StatusCode::OK);
        assert!(first.text().await?.contains("Synthetic Grok answer"));
        fixture.runtime.flush_continuations().await;

        let mut menu = (*fixture
            .runtime
            .global_snapshot()?
            .ok_or("missing synthetic menu")?)
        .clone();
        let target = Arc::make_mut(
            menu.groups
                .get_mut(&fixture.grok_alias)
                .ok_or("missing synthetic route")?,
        );
        target.bindings = Arc::default();
        target.targets[0]
            .upstream
            .as_mut()
            .ok_or("missing synthetic provider")?
            .settings_config["modelCatalog"] =
            json!({"models":[{"model":"grok-4.5","reasoningLevels":["low","high"]}]});
        // Discovery alone keeps ownership. A request-shaping setting still
        // changes the destination and must retain this recovery boundary.
        target.targets[0]
            .upstream
            .as_mut()
            .ok_or("missing synthetic provider")?
            .meta
            .get_or_insert_with(Default::default)
            .prompt_cache_key = Some("synthetic-reconfigured-cache".into());
        fixture.runtime.set_global(menu, 0)?;

        request["messages"]
            .as_array_mut()
            .ok_or("missing synthetic messages")?
            .extend([
                json!({"role":"assistant","content":"Synthetic Grok answer"}),
                json!({"role":"user","content":"Synthetic follow-up"}),
            ]);
        let mut sealed = request.clone();
        sealed["messages"][1]["reasoning_details"] =
            json!([{"type":"reasoning.encrypted","data":"synthetic-sealed-state"}]);
        let rerouted = fixture
            .client
            .post(&fixture.root)
            .bearer_auth(TOKEN)
            .json(&sealed)
            .send()
            .await?;
        assert_eq!(rerouted.status(), StatusCode::OK);
        assert_eq!(
            fixture.sends.load(Ordering::SeqCst),
            2,
            "sealed state rerouted cleanly"
        );
        let next = fixture
            .client
            .post(&fixture.root)
            .bearer_auth(TOKEN)
            .json(&request)
            .send()
            .await?;
        assert_eq!(
            next.status(),
            StatusCode::OK,
            "visible chat is self-contained after refresh, stream={streaming}"
        );
        assert!(next.text().await?.contains("Synthetic Grok answer"));
        assert_eq!(fixture.sends.load(Ordering::SeqCst), 3);
        fixture.stop().await?;
    }
    Ok(())
}

