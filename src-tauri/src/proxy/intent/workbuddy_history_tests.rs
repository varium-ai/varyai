//! Complete visible history can move to a newly selected model; opaque or
//! incomplete continuations still need their original binding.
use super::*;
use crate::{
    database::Database,
    proxy::{server::ProxyServer, ProxyConfig},
};
use axum::{routing::post, Json, Router};
use std::sync::atomic::{AtomicUsize, Ordering};

const TOKEN: &str = "synthetic-workbuddy-history";
const FIRST_ID: &str = "synthetic-call-first";
const SECOND_ID: &str = "synthetic-call-second";
const THIRD_ID: &str = "synthetic-call-third";

fn arguments(index: usize) -> Value {
    json!({"model":format!("synthetic-argument-{index}"),"_fixture_key":"preserved"})
}
fn call(id: &str, index: usize) -> Value {
    json!({"id":id,"type":"function","function":{"name":format!("synthetic_tool_{index}"),"arguments":arguments(index).to_string()}})
}
fn history(model: &str, streaming: bool) -> Value {
    json!({"model":model,"stream":streaming,"messages":[
        {"role":"user","content":"Synthetic first request"},
        {"role":"assistant","content":null,"reasoning_content":"Synthetic visible thought","tool_calls":[call(FIRST_ID,1)]},
        {"role":"tool","tool_call_id":FIRST_ID,"content":"Synthetic first result"},
        {"role":"assistant","content":null,"tool_calls":[call(SECOND_ID,2)]},
        {"role":"tool","tool_call_id":SECOND_ID,"content":"Synthetic second result"},
        {"role":"assistant","content":"Synthetic prior answer","reasoning_content":"Synthetic final thought"},
        {"role":"user","content":"Synthetic Grok follow-up"}
    ]})
}

struct RestoreSecurity(crate::proxy::security::SecurityRuntimeConfig);
impl Drop for RestoreSecurity {
    fn drop(&mut self) {
        crate::proxy::security::runtime::set_security_runtime_for_test(self.0.clone());
    }
}
fn security() -> RestoreSecurity {
    let old = RestoreSecurity((*crate::proxy::security::get_security_runtime()).clone());
    crate::proxy::security::runtime::set_security_runtime_for_test(Default::default());
    old
}

struct Fixture {
    proxy: ProxyServer,
    root: String,
    source_alias: String,
    grok_alias: String,
    client: reqwest::Client,
    runtime: Arc<Runtime>,
    grok: Arc<Session>,
    requests: tokio::sync::mpsc::Receiver<Value>,
    sends: Arc<AtomicUsize>,
    upstream: tokio::task::JoinHandle<()>,
}

fn session(base: &str, id: &str, model: &str, format: &str) -> Arc<Session> {
    let group: RoutingGroup = serde_json::from_value(json!({"id":id,"name":"Synthetic model","revision":0,"client":"codex","enabled":false,"members":[{"id":"direct","providerId":id,"modelId":model}],"defaultMemberId":"direct","fallbackMemberIds":[],"intentRecognitionEnabled":false,"classifierTarget":null,"classificationBudgetMs":2000,"rules":[],"levels":[],"autoGenerated":false,"routing":"ordered"})).unwrap();
    assert_eq!(
        group.routing,
        crate::services::intent_routing::RoutingStrategy::Ordered
    );
    let mut provider = crate::provider::Provider::with_id(
        id.into(),
        "Synthetic upstream".into(),
        json!({"env":{"ANTHROPIC_BASE_URL":base,"ANTHROPIC_API_KEY":"synthetic-upstream"}}),
        None,
    );
    provider.meta = Some(crate::provider::ProviderMeta {
        api_format: Some(format.into()),
        ..Default::default()
    });
    Arc::new(Session {
        group,
        targets: vec![Target {
            provider_id: id.into(),
            model: model.into(),
            fixed_effort: None,
            upstream: Some(provider),
            effort: Default::default(),
            url: format!(
                "{base}{}",
                if format == "openai_chat" {
                    "/chat/completions"
                } else {
                    "/responses"
                }
            )
            .parse()
            .unwrap(),
            headers: http::HeaderMap::new(),
            official: false,
            credentials: None,
            scheduling: Arc::default(),
        }],
        classifier: None,
        client: reqwest::Client::builder().no_proxy().build().unwrap(),
        created: Instant::now(),
        bindings: Arc::default(),
    })
}

impl Fixture {
    async fn new(source_format: &str) -> Result<Self, Box<dyn std::error::Error>> {
        Self::with_targets(source_format, 1).await
    }
    async fn with_targets(
        source_format: &str,
        target_count: usize,
    ) -> Result<Self, Box<dyn std::error::Error>> {
        Self::with_follow_up(source_format, target_count, false).await
    }
    async fn with_follow_up(
        source_format: &str,
        target_count: usize,
        reply_with_call: bool,
    ) -> Result<Self, Box<dyn std::error::Error>> {
        let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await?;
        let address = listener.local_addr()?;
        let (tx, requests) = tokio::sync::mpsc::channel(8);
        let sends = Arc::new(AtomicUsize::new(0));
        let count = sends.clone();
        let app = Router::new().route("/*path", post(move |uri: http::Uri, Json(body): Json<Value>| {
            let tx = tx.clone(); let count = count.clone();
            async move {
                if uri.path().ends_with("responses") {
                    let attempt = count.fetch_add(1, Ordering::SeqCst);
                    let _ = tx.send(body).await;
                    if reply_with_call && attempt == 0 {
                        return Json(json!({"id":"synthetic-grok-tool-reply","object":"response","status":"completed","model":"grok-4.5","output":[{"type":"function_call","id":"synthetic-third-item","call_id":THIRD_ID,"name":"synthetic_tool_3","arguments":arguments(3).to_string(),"status":"completed"}],"usage":{"input_tokens":1,"output_tokens":1}}));
                    }
                    Json(json!({"id":"synthetic-grok-reply","object":"response","status":"completed","model":"grok-4.5","output":[{"type":"message","role":"assistant","content":[{"type":"output_text","text":"Synthetic Grok answer"}]}],"usage":{"input_tokens":1,"output_tokens":1}}))
                } else if uri.path().ends_with("chat/completions") {
                    Json(json!({"id":"synthetic-prior-reply","object":"chat.completion","model":"glm-synthetic","choices":[{"index":0,"message":{"role":"assistant","content":"Synthetic prior answer","reasoning_content":"Synthetic visible thought","tool_calls":[call(FIRST_ID,1),call(SECOND_ID,2)]},"finish_reason":"tool_calls"}],"usage":{"prompt_tokens":1,"completion_tokens":1}}))
                } else {
                    Json(json!({"responseId":"synthetic-prior-reply","modelVersion":"gemini-synthetic","candidates":[{"content":{"role":"model","parts":[{"text":"Synthetic visible thought","thought":true},{"functionCall":{"id":FIRST_ID,"name":"synthetic_tool_1","args":arguments(1)}},{"functionCall":{"id":SECOND_ID,"name":"synthetic_tool_2","args":arguments(2)}}]},"finishReason":"STOP"}],"usageMetadata":{"promptTokenCount":1,"candidatesTokenCount":1}}))
                }
            }
        }));
        let upstream = tokio::spawn(async move {
            let _ = axum::serve(listener, app).await;
        });
        let base = format!("http://{address}");
        let source = session(
            &base,
            "prior-model",
            if source_format == "openai_chat" {
                "glm-synthetic"
            } else {
                "gemini-synthetic"
            },
            source_format,
        );
        let mut grok = session(&base, "new-grok-model", "grok-4.5", "openai_responses");
        if target_count == 2 {
            let other = session(&base, "other-grok-account", "grok-4.5", "openai_responses");
            let group = Arc::make_mut(&mut grok);
            group.group.enabled = true;
            let mut member = other.group.members[0].clone();
            member.id = "other".into();
            group.group.members.push(member);
            group.group.fallback_member_ids.push("other".into());
            group.targets.push(other.targets[0].clone());
        }
        assert_eq!(grok.targets.len(), target_count);
        let source_alias = source.group.alias();
        let grok_alias = grok.group.alias();
        let runtime = Arc::new(Runtime::default());
        runtime.set_global(
            Menu {
                token: "synthetic-menu".into(),
                models: Default::default(),
                default_model: Some(grok_alias.clone()),
                omitted_entries: 0,
                context_settings: Default::default(),
                groups: HashMap::from([
                    (source_alias.clone(), source),
                    (grok_alias.clone(), grok.clone()),
                ]),
            },
            0,
        )?;
        runtime
            .connections
            .install(&crate::services::agent_connections::Receipt {
                app: "workbuddy".into(),
                token: TOKEN.into(),
                model: grok_alias.clone(),
                model_map: Default::default(),
                visible_models: None,
                files: vec![],
                suspended: false,
                applied_at_ms: None,
            })?;
        let proxy = ProxyServer::new(
            ProxyConfig {
                listen_port: 0,
                ..Default::default()
            },
            Arc::new(Database::memory()?),
            None,
        )
        .with_intent_runtime(runtime.clone());
        let info = proxy.start().await?;
        Ok(Self {
            proxy,
            root: format!(
                "http://127.0.0.1:{}/connections/workbuddy/v1/chat/completions",
                info.port
            ),
            source_alias,
            grok_alias,
            client: reqwest::Client::builder().no_proxy().build()?,
            requests,
            runtime,
            grok,
            sends,
            upstream,
        })
    }
    async fn seed_prior_model(&self) -> Result<(), Box<dyn std::error::Error>> {
        let response = self.client.post(&self.root).bearer_auth(TOKEN).json(&json!({"model":self.source_alias,"messages":[{"role":"user","content":"Synthetic initial request"}]})).send().await?;
        assert_eq!(response.status(), StatusCode::OK);
        let body: Value = response.json().await?;
        assert_eq!(
            body["choices"][0]["message"]["tool_calls"]
                .as_array()
                .map(Vec::len),
            Some(2)
        );
        Ok(())
    }
    async fn stop(self) -> Result<(), Box<dyn std::error::Error>> {
        self.proxy.stop().await?;
        self.upstream.abort();
        Ok(())
    }
}

#[tokio::test]
#[serial_test::serial]
async fn workbuddy_can_select_grok_with_complete_visible_tool_history(
) -> Result<(), Box<dyn std::error::Error>> {
    let _security = security();
    for source_format in ["openai_chat", "gemini_native"] {
        for streaming in [false, true] {
            let mut fixture = Fixture::new(source_format).await?;
            fixture.seed_prior_model().await?;
            let response = fixture
                .client
                .post(&fixture.root)
                .bearer_auth(TOKEN)
                .json(&history(&fixture.grok_alias, streaming))
                .send()
                .await?;
            assert_eq!(
                response.status(),
                StatusCode::OK,
                "complete visible {source_format} history should be portable, stream={streaming}"
            );
            assert!(response.text().await?.contains("Synthetic Grok answer"));
            let sent = tokio::time::timeout(Duration::from_secs(2), fixture.requests.recv())
                .await?
                .ok_or("missing synthetic Grok request")?;
            assert_eq!(sent["model"], "grok-4.5");
            assert_eq!(sent["stream"], streaming);
            let input = sent["input"].as_array().ok_or("missing Responses input")?;
            for (id, index, result) in [
                (FIRST_ID, 1, "Synthetic first result"),
                (SECOND_ID, 2, "Synthetic second result"),
            ] {
                let call = input
                    .iter()
                    .find(|item| item["type"] == "function_call" && item["call_id"] == id)
                    .ok_or("missing preserved call")?;
                assert_eq!(
                    serde_json::from_str::<Value>(
                        call["arguments"].as_str().ok_or("missing call arguments")?
                    )?,
                    arguments(index)
                );
                assert!(input
                    .iter()
                    .any(|item| item["type"] == "function_call_output"
                        && item["call_id"] == id
                        && item["output"] == result));
            }
            let encoded = sent.to_string();
            for text in [
                "Synthetic prior answer",
                "Synthetic Grok follow-up",
                "Synthetic visible thought",
                "Synthetic final thought",
            ] {
                assert!(encoded.contains(text));
            }
            assert_eq!(fixture.sends.load(Ordering::SeqCst), 1);
            fixture.stop().await?;
        }
    }
    Ok(())
}

#[tokio::test]
#[serial_test::serial]
async fn workbuddy_incomplete_duplicate_or_opaque_tool_history_never_reaches_grok(
) -> Result<(), Box<dyn std::error::Error>> {
    let _security = security();
    for scenario in [
        "orphan_result",
        "missing_result",
        "duplicate_call_id",
        "duplicate_result",
        "encrypted_reasoning",
        "signed_reasoning",
        "signed_tool_call",
        "signed_text_content",
    ] {
        let fixture = Fixture::new("openai_chat").await?;
        fixture.seed_prior_model().await?;
        let mut request = history(&fixture.grok_alias, false);
        match scenario {
            "orphan_result" => request["messages"][2]["tool_call_id"] = json!("synthetic-orphan"),
            "missing_result" => {
                request["messages"].as_array_mut().unwrap().remove(2);
            }
            "duplicate_call_id" => request["messages"][3]["tool_calls"][0]["id"] = json!(FIRST_ID),
            "duplicate_result" => request["messages"][4]["tool_call_id"] = json!(FIRST_ID),
            "encrypted_reasoning" => {
                request["messages"][1]["reasoning_details"] =
                    json!([{"type":"reasoning.encrypted","data":"synthetic-opaque"}])
            }
            "signed_reasoning" => {
                request["messages"][1]["reasoning_details"] = json!([{"type":"reasoning.text","text":"Synthetic thought","signature":"synthetic-signature"}])
            }
            "signed_text_content" => {
                request["messages"][5]["content"] = json!([{"type":"text","text":"Synthetic signed answer","thoughtSignature":"synthetic-signature"}]);
            }
            "signed_tool_call" => {
                request["messages"][1]["tool_calls"][0]["extra_content"] =
                    json!({"google":{"thought_signature":"synthetic-signature"}})
            }
            _ => unreachable!(),
        }
        let response = fixture
            .client
            .post(&fixture.root)
            .bearer_auth(TOKEN)
            .json(&request)
            .send()
            .await?;
        assert_eq!(response.status(), StatusCode::CONFLICT, "{scenario}");
        let body: Value = response.json().await?;
        assert_eq!(body["error"]["code"], "routing_unknown_continuation");
        assert_eq!(
            fixture.sends.load(Ordering::SeqCst),
            0,
            "{scenario} reached synthetic Grok upstream"
        );
        fixture.stop().await?;
    }
    Ok(())
}

