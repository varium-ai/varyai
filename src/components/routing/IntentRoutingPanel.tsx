function resolveGroupTemplate(
  group: RoutingGroup,
): RoutingTemplate["key"] | undefined {
  if (group.template) return group.template;
  if (group.quotaOrder === "earliest_expiry") return "templateExpiry";
  if (
    group.routing === "fastest" &&
    group.affinity === "turn" &&
    group.contextWindow === -1 &&
    group.firstToken === 30
  )
    return "templateSpeed";
  if (
    group.rules.length === 3 &&
    group.rules.some(
      (rule) => rule.name === "Compaction" && rule.conditions?.compact,
    ) &&
    group.rules.some((rule) => rule.name === "Hard task") &&
    group.rules.some((rule) => rule.name === "Easy task")
  )
    return "templateSmart";
  // Legacy capability presets predate the persisted template key.
  if (
    !group.autoGenerated &&
    (group.routing ?? "ordered") === "ordered" &&
    group.affinity === "turn" &&
    group.contextWindow === -1 &&
    (group.firstToken ?? 0) === 0 &&
    group.patience === 0 &&
    !group.rules.length &&
    !group.classifierTarget &&
    !group.intentRecognitionEnabled &&
    !group.match?.length &&
    !group.off?.length &&
    !group.sink &&
    !group.unlists &&
    !group.levels?.length &&
    group.defaultMemberId === group.members[0]?.id &&
    group.fallbackMemberIds.length === group.members.length - 1 &&
    group.fallbackMemberIds.every(
      (id, index) => id === group.members[index + 1]?.id,
    )
  )
    return "templateCapability";
  return undefined;
}

function withDraftMemberOrder(group: RoutingGroup, members: RoutingMember[]) {
  return {
    ...withRoutingMembers(group, members),
    defaultMemberId: members[0]?.id ?? "",
    fallbackMemberIds: members.slice(1).map(({ id }) => id),
  };
}

function orderGroups(groups: RoutingGroup[], order: string[]) {
  const positions = new Map(order.map((id, index) => [id, index]));
  return groups
    .slice()
    .sort(
      (a, b) =>
        (positions.get(a.id) ?? Infinity) - (positions.get(b.id) ?? Infinity),
    );
}

