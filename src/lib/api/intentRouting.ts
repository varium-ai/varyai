import { invoke } from "@tauri-apps/api/core";

export interface RoutingMember {
  id: string;
  providerId: string;
  modelId: string;
  weight?: number;
  free?: boolean | null;
  effort?: string | null;
}
export interface IntentRule {
  id: string;
  name: string;
  description: string;
  enabled: boolean;
  targetMemberId: string;
  fallbackMemberIds?: string[];
  conditions?: RoutingConditions | null;
  useEffort?: string;
  pause?: boolean;
}
export interface RoutingConditions {
  tokens?: number;
  images?: boolean;
  effort?: string;
  agents?: string[];
  compact?: boolean;
  time?: RoutingTimeWindow | null;
  folders?: string[];
  exceptFolders?: string[];
}
export interface RoutingTimeWindow {
  from: string;
  to: string;
  days?: string[];
  zone?: string;
}
export interface RoutingGroup {
  id: string;
  name: string;
  revision: number;
  client: "global" | "codex";
  enabled: boolean;
  members: RoutingMember[];
  defaultMemberId: string;
  fallbackMemberIds: string[];
  intentRecognitionEnabled: boolean;
  classifierTarget: { providerId: string; modelId: string } | null;
  classificationBudgetMs: number;
  rules: IntentRule[];
  autoGenerated?: boolean;
  routing?:
    | "smart"
    | "ordered"
    | "round_robin"
    | "least_used"
    | "pace"
    | "free_first"
    | "fastest"
    | "weighted"
    | "manual";
  manualMemberId?: string;
  modelAlias?: string;
  contextWindow?: number;
  affinity?: "" | "session" | "turn" | "off" | "strict";
  firstToken?: number;
  patience?: number;
  off?: string[];
  match?: string[];
  unlists?: boolean;
  sink?: boolean;
  levels?: string[];
}
export interface RoutingContextSettings {
  fullWindow: boolean;
  compactAt?: number;
}
export interface RoutingCatalog {
  groups: RoutingGroup[];
  removedGroups?: Array<{ id: string; name: string }>;
  matchedMembers?: Record<string, RoutingMember[]>;
  autoCreate: boolean;
  omittedGroups: number;
  contextSettings?: RoutingContextSettings;
}
export interface RoutingProviderOption {
  id: string;
  name: string;
  icon?: string | null;
  appType?: string;
  taskEligible: boolean;
  classifierEligible: boolean;
  models?: Array<{
    id: string;
    name: string;
    contextWindow?: number | null;
    outputPrice?: number | null;
    maker?: boolean;
    released?: string;
    images?: boolean | null;
    reasoning?: boolean | null;
    reasoningLevels?: string[];
  }>;
}
export interface RoutingPlanPreview {
  groupId: string;
  revision: number;
  candidates: RoutingMember[];
  reason: "rule" | "default_target" | "manual";
  live: false;
}
export interface ClassificationTrial {
  plan: RoutingPlanPreview;
  intentId: string | null;
  outcome:
    | "manual"
    | "matched"
    | "no_match"
    | "no_rules"
    | "privacy"
    | "input_limit"
    | "invalid_output"
    | "request_failed"
    | "unavailable"
    | "timeout";
}
export interface RoutingCatalogStatus {
  providerId: string;
  status: "updated" | "cached" | "unavailable";
  modelCount: number;
  reason?: "notSignedIn" | "requestFailed" | "empty";
}
export const intentRoutingApi = {
  discoverCatalogs: () =>
    invoke<RoutingCatalogStatus[]>("refresh_intent_routing_catalogs", {
      missingOnly: true,
    }),
  refreshCatalogs: () =>
    invoke<RoutingCatalogStatus[]>("refresh_intent_routing_catalogs"),
  list: () => invoke<RoutingCatalog>("list_intent_routing_groups"),
  setAutoCreate: (enabled: boolean) =>
    invoke<void>("set_intent_routing_auto_create", { enabled }),
  autoGroupSkip: () => invoke<string[]>("get_routing_auto_group_skip"),
  setAutoGroupSkip: (ids: string[]) =>
    invoke<void>("set_routing_auto_group_skip", { ids }),
  restore: (id: string) =>
    invoke<void>("restore_discovered_routing_group", { id }),
  setContextSettings: (settings: RoutingContextSettings) =>
    invoke<void>("set_routing_context_settings", { settings }),
  contextSettings: () =>
    invoke<RoutingContextSettings>("get_routing_context_settings"),
  providers: () =>
    invoke<RoutingProviderOption[]>("list_intent_routing_providers"),
  matchedMembers: (group: RoutingGroup) =>
    invoke<RoutingMember[]>("resolve_routing_group_matches", { group }),
  save: (group: RoutingGroup) =>
    invoke<RoutingGroup>("save_intent_routing_group", { group }),
  arrange: (order: string[]) =>
    invoke<void>("arrange_routing_groups", { order }),
  remove: (id: string, revision: number) =>
    invoke<void>("delete_intent_routing_group", { id, revision }),
  trial: (group: RoutingGroup, text: string, consent: boolean) =>
    invoke<ClassificationTrial>("trial_intent_routing_classification", {
      group,
      text,
      consent,
    }),
  preview: (group: RoutingGroup, classification: string) =>
    invoke<RoutingPlanPreview>("preview_intent_routing_plan", {
      group,
      classification,
    }),
};

export interface RoutingExecutionSession {
  token: string;
  baseUrl: string;
  model: string;
  modelCatalogPath: string;
  expiresInSeconds: number;
}
export const routingExecutionApi = {
  start: (group: RoutingGroup, consent: boolean) =>
    invoke<RoutingExecutionSession>("start_intent_routing_session", {
      group,
      consent,
    }),
  stop: (token: string) =>
    invoke<void>("stop_intent_routing_session", { token }),
};

export interface RoutingClientStatus {
  enabled: boolean;
  recoveryPending: boolean;
  orphanedConfig?: boolean;
  orphanCleanupAvailable?: boolean;
  providerEnabled?: boolean;
  omittedEntries?: number;
  configurationIssue?:
    | "provider_missing"
    | "profile_override"
    | "catalog_missing"
    | null;
  nativeCompatibility?:
    | "disabled"
    | "pending"
    | "active"
    | "unsupported"
    | "revoked"
    | "reconnect_required"
    | "recovery_pending";
  groupIds: string[];
}
export const intentRoutingClientApi = {
  status: () => invoke<RoutingClientStatus>("intent_routing_client_status"),
  connect: (consent: boolean) =>
    invoke<RoutingClientStatus>("connect_intent_routing_client", { consent }),
  disconnect: () => invoke<void>("disconnect_intent_routing_client"),
  cleanup: () =>
    invoke<void>("cleanup_intent_routing_orphan", { consent: true }),
};
