export function useRequestLogs({
  filters,
  range,
  page = 0,
  pageSize = 20,
  options,
}: RequestLogsQueryArgs) {
  const key: RequestLogsKey = {
    preset: range.preset,
    customStartDate: range.customStartDate,
    customEndDate: range.customEndDate,
    liveEndTime: range.liveEndTime,
    appType: filters.appType,
    providerName: filters.providerName,
    model: filters.model,
    statusCode: filters.statusCode,
  };
  const queryKey = usageKeys.logs(key, page, pageSize);

  return useQuery({
    queryKey,
    queryFn: () => {
      const effectiveFilters = { ...filters, ...resolveUsageRange(range) };
      return usageApi.getRequestLogs(effectiveFilters, page, pageSize);
    },
    placeholderData: (previousData, previousQuery) => {
      const previousKey = previousQuery?.queryKey;
      if (!previousKey || previousKey.length !== queryKey.length) return;
      // Retain rows only for a page change within the same range and filters.
      const pageIndex = queryKey.length - 2;
      return queryKey.every(
        (part, index) => index === pageIndex || part === previousKey[index],
      )
        ? previousData
        : undefined;
    },
    refetchInterval: options?.refetchInterval ?? DEFAULT_REFETCH_INTERVAL_MS, // 每30秒自动刷新
    refetchIntervalInBackground: options?.refetchIntervalInBackground ?? false,
  });
}

export function useModelPricing() {
  return useQuery({
    queryKey: usageKeys.pricing(),
    queryFn: usageApi.getModelPricing,
  });
}

export function useUpdateModelPricing() {
  const queryClient = useQueryClient();

  return useMutation({
    mutationFn: (params: {
      modelId: string;
      displayName: string;
      inputCost: string;
      outputCost: string;
      cacheReadCost: string;
      cacheCreationCost: string;
    }) =>
      usageApi.updateModelPricing(
        params.modelId,
        params.displayName,
        params.inputCost,
        params.outputCost,
        params.cacheReadCost,
        params.cacheCreationCost,
      ),
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: usageKeys.all });
    },
  });
}

export function useDeleteModelPricing() {
  const queryClient = useQueryClient();

  return useMutation({
    mutationFn: (modelId: string) => usageApi.deleteModelPricing(modelId),
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: usageKeys.all });
    },
  });
}

/** Resolve presentation metadata independently of usage queries and forwarding. */
export function useUsageModelLabels(
  models: string[],
  options?: UsageQueryOptions,
) {
  const queryClient = useQueryClient();
  const ids = Array.from(
    new Set(models.flatMap((model) => getUsageRoutingModelId(model) ?? [])),
  ).sort();
  return useQuery({
    queryKey: usageKeys.modelLabels(ids),
    enabled: ids.length > 0,
    queryFn: async (): Promise<UsageModelLabel[]> => {
      const labels: UsageModelLabel[] = [];
      for (let start = 0; start < ids.length; start += 512) {
        try {
          labels.push(
            ...(await usageApi.getModelLabels(ids.slice(start, start + 512))),
          );
        } catch {
          // Keep the last known names when optional metadata cannot be read.
          const batch = new Set(ids.slice(start, start + 512));
          labels.push(
            ...(
              queryClient.getQueryData<UsageModelLabel[]>(
                usageKeys.modelLabels(ids),
              ) ?? []
            ).filter((label) => batch.has(label.id)),
          );
        }
      }
      return labels;
    },
    placeholderData: (previous) => previous,
    retry: false,
    refetchInterval: options?.refetchInterval ?? DEFAULT_REFETCH_INTERVAL_MS,
    refetchIntervalInBackground: false,
  });
}
